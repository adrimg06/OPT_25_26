# Pedimos al usuario que introduzca la primera nota y la convertimos a número decimal (float)
nota1 = input("Introduce la primera nota: ")

# Pedimos la segunda nota
nota2 = input("Introduce la segunda nota: ")

# Pedimos la tercera nota
nota3 = input("Introduce la tercera nota: ")

# Calculamos el promedio de las tres notas
promedio = (nota1 + nota2 + nota3) / 3

# Mostramos el resultado en pantalla
print("El promedio de las tres notas es:", promedio)
